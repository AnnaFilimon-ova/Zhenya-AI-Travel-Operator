def visa_requirements(country: str) -> dict:
    key = (country or "").strip().lower()
    if not key or len(key) > 80:
        return {"error": "укажи страну", "disclaimer": DISCLAIMER}
    entry = _INDEX.get(key)
    if entry is None and "," in key:
        entry = _INDEX.get(key.split(",")[-1].strip())
    if entry is None:
        return {
            "country": country,
            "status": "unknown",
            "status_text": "в справочнике нет этой страны",
            "stay": "",
            "note": "Нужно проверить правила в консульстве или на travel.mid.ru.",
            "disclaimer": DISCLAIMER,
        }
    status, stay, note = entry
    return {
        "country": country,
        "citizenship": "Россия",
        "status": status,
        "status_text": STATUS_TEXT[status],
        "stay": stay,
        "note": note,
        "disclaimer": DISCLAIMER,
    }
